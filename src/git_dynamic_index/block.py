"""Render and safely replace the generated status block in a Markdown file."""

from __future__ import annotations

import codecs
import html
import os
import re
import stat
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path


class BlockError(Exception):
    """Raised when the status block cannot be read or safely updated."""


START_MARKER = "<!-- AUTO-STATUS-START -->"
END_MARKER = "<!-- AUTO-STATUS-END -->"


@dataclass(frozen=True)
class ChangeItem:
    """One changed path shown in the block."""

    status: str
    path: str


@dataclass(frozen=True)
class StatusData:
    """The Git facts shown in the generated block."""

    branch: str
    commit_sha: str | None
    commit_subject: str | None
    commit_date: str | None
    upstream: str | None
    has_commits: bool = False
    changed: int = 0
    staged: int = 0
    unstaged: int = 0
    untracked: int = 0
    conflicts: int = 0
    changes: tuple[ChangeItem, ...] = ()
    omitted: int = 0


_CONTROL_RE = re.compile(r"[\x00-\x1f\x7f]+")


def _clean_inline(value: str) -> str:
    """Collapse control characters and whitespace into single spaces."""
    return " ".join(_CONTROL_RE.sub(" ", value).split())


def _inline_code(value: str) -> str:
    """Render a code span, widening the fence when the value has backticks."""
    fence = "`"
    while fence in value:
        fence += "`"
    if value.startswith("`") or value.endswith("`"):
        return f"{fence} {value} {fence}"
    return f"{fence}{value}{fence}"


def _display_path(value: str) -> str:
    """Keep paths readable without letting control characters break the block."""
    return value.replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t")


def _last_commit(data: StatusData) -> str:
    if data.commit_sha:
        subject = html.escape(
            _clean_inline(data.commit_subject or "(no message)"), quote=False
        )
        date = _clean_inline(data.commit_date or "")
        suffix = f" ({date})" if date else ""
        return f"{_inline_code(_clean_inline(data.commit_sha))} {subject}{suffix}"
    if data.has_commits:
        return "none (only index updates)"
    return "none yet"


def working_tree_summary(data: StatusData) -> str:
    if data.changed == 0:
        return "clean"
    return (
        f"{data.changed} changed "
        f"({data.staged} staged, {data.unstaged} unstaged, "
        f"{data.untracked} untracked, {data.conflicts} conflicts)"
    )


def _changed_files(data: StatusData) -> str:
    items = [
        f"{_inline_code(_clean_inline(item.status))} "
        f"{_inline_code(_display_path(item.path))}"
        for item in data.changes
    ]
    rendered = ", ".join(items)
    if data.omitted:
        rendered += f" (+{data.omitted} more; counts are complete)"
    return rendered


def _marker_positions(
    text: str,
) -> tuple[list[str], list[tuple[int, int]], list[tuple[int, int]]]:
    """Find marker lines and their character offsets."""
    lines = text.splitlines(keepends=True)
    starts: list[tuple[int, int]] = []
    ends: list[tuple[int, int]] = []
    offset = 0

    for line_number, line in enumerate(lines, start=1):
        stripped = line.strip()
        if stripped == START_MARKER:
            starts.append((line_number, offset))
        elif stripped == END_MARKER:
            ends.append((line_number, offset))
        offset += len(line)

    return lines, starts, ends


def _find_markers(text: str) -> tuple[int, int]:
    """Return the character span between the two marker lines."""
    lines, starts, ends = _marker_positions(text)

    if len(starts) != 1:
        raise BlockError(f"expected exactly one start marker, found {len(starts)}")
    if len(ends) != 1:
        raise BlockError(f"expected exactly one end marker, found {len(ends)}")

    start_line, start_offset = starts[0]
    end_line, end_offset = ends[0]
    if start_line >= end_line:
        raise BlockError(
            f"start marker (line {start_line}) must appear before "
            f"end marker (line {end_line})"
        )

    inner_start = start_offset + len(lines[start_line - 1])
    return inner_start, end_offset


def _detect_newline(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def render_body(data: StatusData, newline: str = "\n") -> str:
    """Render everything that belongs between the two markers."""
    if newline not in ("\n", "\r\n"):
        raise ValueError("newline must be '\\n' or '\\r\\n'")

    lines = [
        "<!-- Generated by git-dynamic-index from local Git state; "
        "edits inside the markers will be overwritten. -->",
        "",
        "## Project status",
        "",
        f"- **Branch**: {_inline_code(_clean_inline(data.branch))}",
        f"- **Last commit (excl. this file)**: {_last_commit(data)}",
        f"- **Working tree (excl. this file)**: {working_tree_summary(data)}",
    ]
    if data.changes:
        lines.append(f"- **Changed files**: {_changed_files(data)}")
    lines.append(
        f"- **Upstream**: "
        f"{_inline_code(_clean_inline(data.upstream)) if data.upstream else 'not set'}"
    )
    return newline.join(lines) + newline


def render_document(
    text: str,
    data: StatusData,
    newline: str | None = None,
) -> str:
    """Replace the block body while preserving everything outside the markers."""
    inner_start, inner_end = _find_markers(text)
    chosen_newline = newline if newline is not None else _detect_newline(text)
    body = render_body(data, chosen_newline)
    return text[:inner_start] + body + text[inner_end:]


@dataclass(frozen=True)
class UpdateResult:
    path: Path
    changed: bool


@dataclass(frozen=True)
class FileInspection:
    path: Path
    exists: bool
    valid: bool
    current: bool
    detail: str


_REPLACE_RETRIES = 3
_REPLACE_DELAY_SECONDS = 0.05


def _decode(path: Path, raw: bytes) -> tuple[str, bool]:
    has_bom = raw.startswith(codecs.BOM_UTF8)
    try:
        text = raw.decode("utf-8-sig" if has_bom else "utf-8")
    except UnicodeDecodeError as exc:
        raise BlockError(f"{path} is not valid UTF-8") from exc
    return text, has_bom


def _atomic_write(
    path: Path,
    payload: bytes,
    default_mode: int | None = None,
) -> None:
    descriptor, temp_name = tempfile.mkstemp(
        prefix=f".{path.name}.",
        suffix=".tmp",
        dir=path.parent,
    )
    temp_path = Path(temp_name)

    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())

        try:
            mode = stat.S_IMODE(path.stat().st_mode)
        except OSError:
            mode = default_mode
        if mode is not None:
            try:
                os.chmod(temp_path, mode)
            except OSError:
                pass

        last_error: PermissionError | None = None
        for attempt in range(_REPLACE_RETRIES):
            try:
                os.replace(temp_path, path)
                return
            except PermissionError as exc:
                last_error = exc
                if attempt + 1 < _REPLACE_RETRIES:
                    time.sleep(_REPLACE_DELAY_SECONDS)

        raise BlockError(
            f"could not replace {path}; close the file in other applications "
            "and retry"
        ) from last_error
    finally:
        try:
            temp_path.unlink()
        except OSError:
            pass


def _payload_for(text: str, has_bom: bool, data: StatusData) -> bytes:
    new_text = render_document(text, data)
    payload = new_text.encode("utf-8")
    if has_bom:
        payload = codecs.BOM_UTF8 + payload
    return payload


def _new_document(title: str, newline: str) -> str:
    clean_title = html.escape(_clean_inline(title) or "Project", quote=False)
    return (
        f"# {clean_title}{newline}{newline}"
        f"{START_MARKER}{newline}{END_MARKER}{newline}"
    )


def _append_markers(text: str, newline: str) -> str:
    if text:
        if not text.endswith(newline):
            text += newline + newline
        elif not text.endswith(newline + newline):
            text += newline
    return f"{text}{START_MARKER}{newline}{END_MARKER}{newline}"


def update_file(path: Path, data: StatusData) -> UpdateResult:
    """Render and atomically update the block; leave an unchanged file untouched."""
    path = Path(path)

    if path.is_symlink():
        raise BlockError(f"{path} is a symbolic link; refusing to replace it")
    if not path.exists():
        raise BlockError(f"{path} does not exist")
    if not path.is_file():
        raise BlockError(f"{path} is not a regular file")

    original = path.read_bytes()
    text, has_bom = _decode(path, original)
    payload = _payload_for(text, has_bom, data)

    if payload == original:
        return UpdateResult(path=path, changed=False)

    _atomic_write(path, payload)
    return UpdateResult(path=path, changed=True)


def ensure_file(path: Path, data: StatusData, title: str) -> UpdateResult:
    """Create or extend a document with the marker pair, then render it."""
    path = Path(path)

    if path.is_symlink():
        raise BlockError(f"{path} is a symbolic link; refusing to replace it")
    if path.exists() and not path.is_file():
        raise BlockError(f"{path} is not a regular file")

    if path.exists():
        original = path.read_bytes()
        text, has_bom = _decode(path, original)
        newline = _detect_newline(text)
        _, starts, ends = _marker_positions(text)

        if not starts and not ends:
            if text:
                text = _append_markers(text, newline)
            else:
                text = _new_document(title, newline)
        else:
            _find_markers(text)

        payload = _payload_for(text, has_bom, data)
        if payload == original:
            return UpdateResult(path=path, changed=False)
        _atomic_write(path, payload)
        return UpdateResult(path=path, changed=True)

    if not path.parent.exists():
        raise BlockError(f"parent directory {path.parent} does not exist")
    if not path.parent.is_dir():
        raise BlockError(f"parent path {path.parent} is not a directory")

    text = _new_document(title, "\n")
    payload = _payload_for(text, False, data)
    _atomic_write(path, payload, default_mode=0o644)
    return UpdateResult(path=path, changed=True)


def inspect_file(path: Path, data: StatusData) -> FileInspection:
    """Check markers and freshness without modifying the document."""
    path = Path(path)

    if path.is_symlink():
        return FileInspection(
            path, True, False, False, "symbolic link; refusing to replace it"
        )
    if not path.exists():
        return FileInspection(path, False, False, False, "file does not exist; run gdi init")
    if not path.is_file():
        return FileInspection(path, True, False, False, "not a regular file")

    original = path.read_bytes()
    try:
        text, has_bom = _decode(path, original)
    except BlockError as exc:
        return FileInspection(path, True, False, False, str(exc))

    _, starts, ends = _marker_positions(text)
    if not starts and not ends:
        return FileInspection(path, True, False, False, "markers not found; run gdi init")

    try:
        payload = _payload_for(text, has_bom, data)
    except BlockError as exc:
        return FileInspection(path, True, False, False, str(exc))

    if payload == original:
        return FileInspection(path, True, True, True, "up to date")
    return FileInspection(path, True, True, False, "out of date; run gdi update")
